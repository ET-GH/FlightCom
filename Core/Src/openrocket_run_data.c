const OpenRocketSample *openrocket_run_get(size_t index)
{
    if (index >= openrocket_run_sample_count) {
        return NULL;
    }
    return &openrocket_run_samples[index];
}

static size_t lower_bound_time(float time_s)
{
    size_t low = 0U;
    size_t high = openrocket_run_sample_count;

    while (low < high) {
        const size_t mid = low + ((high - low) / 2U);
        if (openrocket_run_samples[mid].time_s < time_s) {
            low = mid + 1U;
        } else {
            high = mid;
        }
    }
    return low;
}

const OpenRocketSample *openrocket_run_find_nearest(float time_s)
{
    size_t upper;
    const OpenRocketSample *before;
    const OpenRocketSample *after;

    if (openrocket_run_sample_count == 0U) {
        return NULL;
    }

    upper = lower_bound_time(time_s);
    if (upper == 0U) {
        return &openrocket_run_samples[0];
    }
    if (upper >= openrocket_run_sample_count) {
        return &openrocket_run_samples[openrocket_run_sample_count - 1U];
    }

    before = &openrocket_run_samples[upper - 1U];
    after = &openrocket_run_samples[upper];
    if ((time_s - before->time_s) <= (after->time_s - time_s)) {
        return before;
    }
    return after;
}

bool openrocket_run_interpolate(float time_s, OpenRocketSample *out_sample)
{
    size_t upper;
    const OpenRocketSample *a;
    const OpenRocketSample *b;
    float span;
    float fraction;

    if ((out_sample == NULL) || (openrocket_run_sample_count == 0U)) {
        return false;
    }

    upper = lower_bound_time(time_s);
    if (upper == 0U) {
        *out_sample = openrocket_run_samples[0];
        return true;
    }
    if (upper >= openrocket_run_sample_count) {
        *out_sample = openrocket_run_samples[openrocket_run_sample_count - 1U];
        return true;
    }

    a = &openrocket_run_samples[upper - 1U];
    b = &openrocket_run_samples[upper];
    span = b->time_s - a->time_s;
    if (span <= 0.0f) {
        *out_sample = *a;
        return true;
    }

    fraction = (time_s - a->time_s) / span;
    out_sample->time_s = time_s;
    out_sample->altitude_m =
        a->altitude_m + fraction * (b->altitude_m - a->altitude_m);
    out_sample->velocity_mps =
        a->velocity_mps + fraction * (b->velocity_mps - a->velocity_mps);
    out_sample->acceleration_mps2 =
        a->acceleration_mps2 + fraction *
        (b->acceleration_mps2 - a->acceleration_mps2);
    return true;
}

